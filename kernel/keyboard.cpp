char keyboard_poll_char()
{
    unsigned char status;

    // ============================================================
    // KEYBOARD CONTROLLER STATUS
    // ============================================================

    unsigned short status_port = 0x64;

    asm volatile (
        "inb %1, %0"
        : "=a"(status)
        : "Nd"(status_port)
    );

    // No keyboard data available.
    if (!(status & 1))
    {
        return 0;
    }

    // ============================================================
    // READ SCANCODE
    // ============================================================

    unsigned char scancode;

    unsigned short data_port = 0x60;

    asm volatile (
        "inb %1, %0"
        : "=a"(scancode)
        : "Nd"(data_port)
    );

   
   // ============================================================
   // EXTENDED SCANCODE PREFIX
   // ============================================================

   if (scancode == 0xE0)
   {
        extended_scancode = true;
          return 0;
   }

   // ============================================================
   // EXTENDED KEY
   // ============================================================

    if (extended_scancode)
    { 
    extended_scancode = false;

    if (scancode == 0x48)
    {
        return KEY_ARROW_UP;
    }

    if (scancode == 0x50)
    {
        return KEY_ARROW_DOWN;
    }

    return 0;
}

   
    // ============================================================
    // LEFT SHIFT PRESSED
    // ============================================================

    if (scancode == 0x2A)
    {
        shift_pressed = true;
        return 0;
    }

    // ============================================================
    // RIGHT SHIFT PRESSED
    // ============================================================

    if (scancode == 0x36)
    {
        shift_pressed = true;
        return 0;
    }

    // ============================================================
    // LEFT SHIFT RELEASED
    // ============================================================

    if (scancode == 0xAA)
    {
        shift_pressed = false;
        return 0;
    }

    // ============================================================
    // RIGHT SHIFT RELEASED
    // ============================================================

    if (scancode == 0xB6)
    {
        shift_pressed = false;
        return 0;
    }

    // ============================================================
    // OTHER KEY RELEASE
    // ============================================================

    if (scancode & 0x80)
    {
        return 0;
    }

    // ============================================================
    // SHIFTED CHARACTER
    // ============================================================

    if (shift_pressed)
    {
        // UK keyboard backslash key.
        if (scancode == 0x56)
        {
            return '|';
        }

        return scancode_to_shifted[scancode];
    }

    // ============================================================
    // NORMAL CHARACTER
    // ============================================================

    if (scancode == 0x56)
    {
        return '\\';
    }

    return scancode_to_ascii[scancode];
}

